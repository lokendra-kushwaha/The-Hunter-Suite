def _deep_merge_blueprints(ai_blueprint: Dict, user_blueprint: Dict) -> Dict:
    """
    Intelligently merges the AI-generated blueprint with user-defined overrides.
    
    Args:
        ai_blueprint (Dict): The comprehensive blueprint generated by the Scanner.
        user_blueprint (Dict): The specific overrides provided by the user.
        
    Returns:
        Dict: A unified execution blueprint where human rules overwrite AI rules.
    """
    merged = copy.deepcopy(ai_blueprint)
    for col, rules in user_blueprint.items():
        if col in merged:
            merged[col].update(rules) 
        else:
            merged[col] = rules       
    return merged


