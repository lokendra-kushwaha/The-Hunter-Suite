def auto_shape_handler(func: Callable) -> Callable:
    """
    The Smart Decorator for `nh.tools.*` ecosystem.
    
    Acts as an independent interceptor for analytical functions. If a 3D dataset 
    is passed to a tool wrapped in this decorator, it automatically flattens the 
    data, executes the algorithm, and reconstructs the 3D matrix seamlessly. 
    If the data is natively 2D, it bypasses flattening instantly via O(1) checks.

    Args:
        func (Callable): The tool function to wrap (e.g., `knn_imputer`).

    Returns:
        Callable: The wrapped, dimensionally-agnostic tool.
    """
    @wraps(func)
    def wrapper(data: pd.DataFrame, bypass_flattening: bool = False, *args, **kwargs):
        if bypass_flattening:
            logger.debug("Decorator bypass active. Injecting raw data into tool.")
            return func(data, *args, **kwargs)
            
        from nullhunter.nodes.flattener import SchemaFlattener
        flattener = SchemaFlattener()
        
        # Self-Firing Protocol
        _, keep_flattener = flattener.evaluate(data, user_bypass=False)
        
        if not keep_flattener:
            return func(data, *args, **kwargs)
            
        # Transparent Shape Shifting
        flat_data = flattener.transform(data)
        processed_data = func(flat_data, *args, **kwargs)
        
        from nullhunter.nodes.reconstructor import SchemaReconstructor
        reconstructor = SchemaReconstructor()
        return reconstructor.rebuild(
            processed_data, 
            flattener.schema_blueprint.get('reconstruction_mapping', {})
        )
        
    return wrapper


# ==========================================
# ISOLATED PASS-1 WORKER (For Loop-Less MapReduce)
# ==========================================
def _pass1_discovery_worker(
    chunk: pd.DataFrame, 
    keep_flat: bool, 
    keep_opt: bool, 
    flat_blueprint: Dict, 
    opt_headers: list
) -> Dict[str, Any]:
    """
    Isolated worker for Pass-1 Map phase. Applies O(1) bypasses instantly.
    
    Args:
        chunk (pd.DataFrame): The raw data chunk.
        keep_flat (bool): Flag to keep Flattener active.
        keep_opt (bool): Flag to keep Optimizer active.
        flat_blueprint (Dict): Asset 1 (Master Ledger).
        opt_headers (list): Asset 2 (Optimized Metadata).
        
    Returns:
        Dict[str, Any]: Statistical moments for the chunk via Scanner.
    """
    # 1. Brutal O(1) Bypasses
    if keep_flat:
        from nullhunter.nodes.flattener import SchemaFlattener
        flattener = SchemaFlattener(memory_safe_copy=True)
        flattener.schema_blueprint = flat_blueprint
        chunk = flattener.transform(chunk)
        
    if keep_opt:
        chunk.columns = opt_headers
        
    # 2. Extract Math Moments (Map Phase)
    from nullhunter.nodes.scanner import extract_chunk_statistics
    return extract_chunk_statistics(chunk)




